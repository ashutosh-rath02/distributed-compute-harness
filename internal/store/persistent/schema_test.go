// buildLegacyDB writes a database the way a manager from before schema
// versions did: the current layout, with data, and no version record.
func buildLegacyDB(t *testing.T, path string) {
	t.Helper()
	s, err := Open(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := s.UpsertJob(domain.Job{ID: "job-1"}); err != nil {
		t.Fatal(err)
	}
	if err := s.PutPolicy(domain.DefaultPolicy()); err != nil {
		t.Fatal(err)
	}
	s.Close()
	raw, err := bbolt.Open(path, 0o600, nil)
	if err != nil {
		t.Fatal(err)
	}
	if err := raw.Update(func(tx *bbolt.Tx) error { return tx.Bucket(settingsBucket).Delete(schemaKey) }); err != nil {
		t.Fatal(err)
	}
	raw.Close()
}

var updateFixture = flag.Bool("update", false, "regenerate testdata/schema-v1.bbolt from the CURRENT code (only ever do this while the current layout still IS version 1)")

const fixtureV1 = "testdata/schema-v1.bbolt"

// legacyDB is a copy of the committed version-1 database. It was written
// once, by the manager as it stood when schema versions were introduced, so
// it keeps testing the real old layout after the code moves on.
func legacyDB(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile(fixtureV1)
	if err != nil {
		t.Fatalf("missing fixture (generate with: go test ./internal/store/persistent -run TestGenerateFixture -update): %v", err)
	}
	path := filepath.Join(t.TempDir(), "manager.db")
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestGenerateFixture(t *testing.T) {
	if !*updateFixture {
		t.Skip("only with -update")
	}
	if CurrentSchema != 1 {
		t.Fatal("the version-1 fixture must be generated by version-1 code")
	}
	os.MkdirAll("testdata", 0o755)
	tmp := filepath.Join(t.TempDir(), "gen.db")
	buildLegacyDB(t, tmp)
	data, _ := os.ReadFile(tmp)
	if err := os.WriteFile(fixtureV1, data, 0o644); err != nil {
		t.Fatal(err)
	}
}

func version(t *testing.T, s *Store) int {
	t.Helper()
	v, err := s.SchemaVersion()
	if err != nil {
		t.Fatal(err)
	}
	return v
}

func TestFreshDatabaseIsStampedCurrent(t *testing.T) {
	s, err := Open(filepath.Join(t.TempDir(), "m.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	if v := version(t, s); v != CurrentSchema {
		t.Fatalf("fresh database version = %d, want %d", v, CurrentSchema)
	}
}

func TestLegacyDatabaseOpensAsVersionOneWithItsData(t *testing.T) {
	path := legacyDB(t)
	s, err := Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	if v := version(t, s); v != 1 {
		t.Fatalf("legacy database version = %d, want 1", v)
	}
	jobs, _ := s.ListJobs()
	if len(jobs) != 1 || jobs[0].ID != "job-1" {
		t.Fatalf("legacy data lost: %+v", jobs)
	}
}

func twoSteps(order *[]int) plan {
	step := func(to int) migration {
		return migration{To: to, Name: "step", Up: func(tx *bbolt.Tx) error {
			*order = append(*order, to)
			return tx.Bucket(settingsBucket).Put([]byte("migrated-"+string(rune('0'+to))), []byte("yes"))
		}}
	}
	return plan{current: 3, steps: []migration{step(2), step(3)}}
}

func TestMigrationsRunInOrderOnceWithASafetyCopy(t *testing.T) {
	path := legacyDB(t)
	var order []int
	s, err := open(path, twoSteps(&order))
	if err != nil {
		t.Fatal(err)
	}
	if v := version(t, s); v != 3 || len(order) != 2 || order[0] != 2 || order[1] != 3 {
		t.Fatalf("version %d, steps %v", v, order)
	}
	s.Close()

	copies, _ := filepath.Glob(path + ".pre-upgrade-v1-to-v3-*.bak")
	if len(copies) != 1 {
		t.Fatalf("want one safety copy, found %v", copies)
	}
	info, err := Inspect(copies[0])
	if err != nil || info.SchemaVersion != 1 || info.Jobs != 1 {
		t.Fatalf("safety copy should be the old database intact: %+v %v", info, err)
	}

	// Idempotent: opening again runs nothing and makes no second copy.
	order = nil
	s, err = open(path, twoSteps(&order))
	if err != nil {
		t.Fatal(err)
	}
	s.Close()
	if len(order) != 0 {
		t.Fatalf("migrations re-ran: %v", order)
	}
	if again, _ := filepath.Glob(path + ".pre-upgrade-*"); len(again) != 1 {
		t.Fatalf("second open made another copy: %v", again)
	}
}

func TestFailedMigrationStepLeavesTheVersionAndData(t *testing.T) {
	path := legacyDB(t)
	boom := errors.New("boom")
	p := plan{current: 3, steps: []migration{
		{To: 2, Name: "ok", Up: func(tx *bbolt.Tx) error { return tx.Bucket(settingsBucket).Put([]byte("a"), []byte("1")) }},
		{To: 3, Name: "bad", Up: func(tx *bbolt.Tx) error {
			tx.Bucket(settingsBucket).Put([]byte("b"), []byte("1"))
			return boom
		}},
	}}
	if _, err := open(path, p); err == nil || !strings.Contains(err.Error(), "step 3") {
		t.Fatalf("want a step-3 failure, got %v", err)
	}
	raw, err := bbolt.Open(path, 0o600, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer raw.Close()
	raw.View(func(tx *bbolt.Tx) error {
		if v, _ := readVersion(tx); v != 2 {
			t.Errorf("version after failed step 3 = %d, want 2 (step 2 committed on its own)", v)
		}
		if tx.Bucket(settingsBucket).Get([]byte("b")) != nil {
			t.Error("the failed step's writes were kept")
		}
		return nil
	})
}

func TestNewerDatabaseIsRefusedUntouched(t *testing.T) {
	path := legacyDB(t)
	raw, _ := bbolt.Open(path, 0o600, nil)
	raw.Update(func(tx *bbolt.Tx) error { return stampVersion(tx, CurrentSchema+5) })
	raw.Close()
	before, _ := os.ReadFile(path)

	_, err := Open(path)
	var se *SchemaError
	if !errors.As(err, &se) || !errors.Is(err, ErrSchemaTooNew) || se.Found != CurrentSchema+5 {
		t.Fatalf("want a SchemaError for a newer database, got %v", err)
	}
	if !strings.Contains(err.Error(), "newer manager") {
		t.Errorf("message should say why: %v", err)
	}
	after, _ := os.ReadFile(path)
	if string(before) != string(after) {
		t.Error("a refused database was modified")
	}
	if _, err := Inspect(path); !errors.Is(err, ErrSchemaTooNew) {
		t.Errorf("Inspect should flag it too: %v", err)
	}
}

func TestMigrationListMustBeOrdered(t *testing.T) {
	bad := plan{current: 2, steps: []migration{{To: 3, Up: func(*bbolt.Tx) error { return nil }}}}
	if _, err := open(filepath.Join(t.TempDir(), "x.db"), bad); err == nil {
		t.Fatal("an out-of-order migration list was accepted")
	}
	if err := defaultPlan().validate(); err != nil {
		t.Fatalf("shipped migrations invalid: %v", err)
	}
}

func TestDiskFullDegradesThenRecovers(t *testing.T) {
	s, err := Open(filepath.Join(t.TempDir(), "m.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	s.InjectWriteFault(ErrNoSpace)
	if err := s.UpsertJob(domain.Job{ID: "j"}); !IsNoSpace(err) {
		t.Fatalf("write error = %v", err)
	}
	if h := s.Health(); !h.Degraded || h.Reason == "" {
		t.Fatalf("health = %+v", h)
	}
	if jobs, err := s.ListJobs(); err != nil || len(jobs) != 0 {
		t.Fatalf("reads must keep working: %v %v", jobs, err)
	}
	if s.Probe() == nil {
		t.Fatal("probe should fail while the disk is full")
	}
	s.InjectWriteFault(nil)
	if err := s.Probe(); err != nil {
		t.Fatal(err)
	}
	if h := s.Health(); h.Degraded {
		t.Fatalf("still degraded after a good write: %+v", h)
	}
	if err := s.UpsertJob(domain.Job{ID: "j"}); err != nil {
		t.Fatal(err)
	}
}

func TestOtherErrorsDoNotMarkTheDiskBad(t *testing.T) {
	s, _ := Open(filepath.Join(t.TempDir(), "m.db"))
	defer s.Close()
	s.InjectWriteFault(errors.New("some bug"))
	s.UpsertJob(domain.Job{ID: "j"})
	if s.Health().Degraded {
		t.Fatal("an unrelated error degraded the store")
	}
}
